package ru.kiviuly.mg.api.game;

/** Фазы жизненного цикла сессии. */
public enum GamePhase
{
    /** Ожидание игроков в лобби (набор до минимума). */
    LOBBY,
    /** Обратный отсчёт до старта (минимум набран). */
    COUNTDOWN,
    /** Матч идёт. */
    RUNNING,
    /** Матч завершён, идёт объявление/очистка. */
    ENDING
}
